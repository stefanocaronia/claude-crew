// "1 task", "2 tasks", "11 tasks" in Arabic, whose plural changes with the number.
function arabicTasks(count: number): string
{
    const rest = count % 100;
    return count === 0 ? "لا مهام" : count === 1 ? "مهمة واحدة" : count === 2 ? "مهمتان" : rest >= 3 && rest <= 10 ? `${count} مهام` : `${count} مهمة`;
}
