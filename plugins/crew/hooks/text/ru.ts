// The Russian plural of "task" after a number: 1 задача, 2 задачи, 5 задач.
function russianTasks(count: number): string
{
    const last = count % 10;
    const lastTwo = count % 100;
    return last === 1 && lastTwo !== 11 ? "задача" : last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? "задачи" : "задач";
}
