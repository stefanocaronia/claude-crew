// "1 task", "2 tasks", "11 tasks" in Arabic, whose plural changes with the number.
function arabicTasks(count: number): string
{
    const rest = count % 100;
    return count === 0 ? "لا مهام" : count === 1 ? "مهمة واحدة" : count === 2 ? "مهمتان" : rest >= 3 && rest <= 10 ? `${count} مهام` : `${count} مهمة`;
}

// The Russian plural of "task" after a number: 1 задача, 2 задачи, 5 задач.
function russianTasks(count: number): string
{
    const last = count % 10;
    const lastTwo = count % 100;
    return last === 1 && lastTwo !== 11 ? "задача" : last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? "задачи" : "задач";
}
